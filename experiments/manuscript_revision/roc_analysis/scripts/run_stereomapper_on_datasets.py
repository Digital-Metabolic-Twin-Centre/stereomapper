import os
import pandas as pd
from pathlib import Path
import subprocess

def run_stereomapper(input_dir, output_file):
    """
    Run Stereomapper on the benchmarking datasets generated by gen_benchmarking_datasets.py.
    This will produce confidence scores for each pair in the datasets, which can then be used for ROC analysis.
    """

    cmd = ["stereomapper", "run", "-d", str(input_dir), "-o", str(output_file)]
    print(f"Running Stereomapper with command: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        print(f"Error running Stereomapper: {result.stderr}")
    else:
        print(f"Stereomapper completed successfully. Output saved to {output_file}")

def main():
    input_dir_enantiomer = "/home/jackmcgoldrick/repos/stereomapper_original_release/experiments/manuscript_revision/roc_analysis/data/molfiles/enantiomer_dataset_molfiles"

    output_file_enantiomer = "/home/jackmcgoldrick/repos/stereomapper_original_release/experiments/manuscript_revision/roc_analysis/results/enantiomer_score_benchmarking.sqlite"

    run_stereomapper(input_dir_enantiomer, output_file_enantiomer)

if __name__ == "__main__":    main()